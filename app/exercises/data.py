"""Ćwiczenia - jednolite źródło danych (single source of truth).

Wszystkie 58 unikalnych ćwiczeń z puli treningowej zdefiniowane raz, z walidacją Pydantic.
Pula (_exercise_pool) budowana jest z tych danych przez `app.exercises.loader`.

Uwagi językowe: wszystkie teksty są tylko po polsku lub po angielsku.
"""

from __future__ import annotations

from pydantic import BaseModel, field_validator, model_validator
from typing import Final

# ---------------------------------------------------------------------------
# Słowniki wartości (fixed vocabularies)
# ---------------------------------------------------------------------------

MUSCLE_GROUPS: Final[frozenset[str]] = frozenset({
    "chest", "back", "lats", "traps", "rear_delts", "front_delts", "side_delts",
    "quads", "hamstrings", "glutes", "calves", "abs", "obliques", "lower_back",
    "biceps", "triceps", "forearms", "cardio", "full_body",
})

EQUIPMENT: Final[frozenset[str]] = frozenset({
    "barbell", "dumbbell", "kettlebell", "machine", "cable", "bench",
    "pullup_bar", "dip_station", "bands", "bodyweight",
})

MOVEMENT_PATTERNS: Final[frozenset[str]] = frozenset({
    "squat", "hinge", "horizontal_push", "vertical_push", "horizontal_pull",
    "vertical_pull", "lunge", "carry", "core", "isolation", "cardio",
})

LEVELS: Final[frozenset[str]] = frozenset({"beginner", "intermediate", "advanced"})
EXERCISE_TYPES: Final[frozenset[str]] = frozenset({"compound", "isolation"})
CONTRAINDICATIONS: Final[frozenset[str]] = frozenset({
    "low_back", "shoulder", "knee", "wrist", "elbow", "neck",
})

DESCRIPTION_STATUSES: Final[frozenset[str]] = frozenset({"needs_review", "approved"})


class ExerciseDescription(BaseModel):
    summary: str
    setup: str = ""
    execution: list[str] = []
    cues: list[str] = []
    common_mistakes: list[str] = []
    easier_variant: str | None = None
    harder_variant: str | None = None
    breathing: str = ""


class Exercise(BaseModel):
    id: str
    name_pl: str
    name_en: str
    aliases: list[str] = []
    primary_muscles: list[str]
    secondary_muscles: list[str] = []
    movement_pattern: str
    equipment: list[str]
    level: str
    type: str
    contraindications: list[str] = []
    sets_range: str = "3-4"
    reps_range: str = "8-12"
    description: ExerciseDescription
    description_status: str = "needs_review"

    @field_validator("id")
    @classmethod
    def _id_slug(cls, v: str) -> str:
        if not v or not v.islower() or " " in v:
            raise ValueError(f"id musi byc slugiem lowercase bez spacji: {v!r}")
        return v

    @field_validator("primary_muscles", "secondary_muscles")
    @classmethod
    def _validate_muscles(cls, v: list[str]) -> list[str]:
        bad = [m for m in v if m not in MUSCLE_GROUPS]
        if bad:
            raise ValueError(f"Nieznane grupy mesniowe: {bad}")
        return v

    @field_validator("equipment")
    @classmethod
    def _validate_equipment(cls, v: list[str]) -> list[str]:
        bad = [e for e in v if e not in EQUIPMENT]
        if bad:
            raise ValueError(f"Nieznany sprzedz: {bad}")
        return v

    @field_validator("movement_pattern")
    @classmethod
    def _validate_pattern(cls, v: str) -> str:
        if v not in MOVEMENT_PATTERNS:
            raise ValueError(f"Nieznany wzorzec ruchu: {v!r}")
        return v

    @field_validator("level")
    @classmethod
    def _validate_level(cls, v: str) -> str:
        if v not in LEVELS:
            raise ValueError(f"Nieznany poziom: {v!r}")
        return v

    @field_validator("type")
    @classmethod
    def _validate_type(cls, v: str) -> str:
        if v not in EXERCISE_TYPES:
            raise ValueError(f"Nieznany typ: {v!r}")
        return v

    @field_validator("contraindications")
    @classmethod
    def _validate_contraindications(cls, v: list[str]) -> list[str]:
        bad = [c for c in v if c not in CONTRAINDICATIONS]
        if bad:
            raise ValueError(f"Nieznane przeciwwskazania: {bad}")
        return v

    @field_validator("description_status")
    @classmethod
    def _validate_status(cls, v: str) -> str:
        if v not in DESCRIPTION_STATUSES:
            raise ValueError(f"Nieznany status opisu: {v!r}")
        return v

    @model_validator(mode="after")
    def _check_only_pl_en(cls, m: "Exercise") -> "Exercise":
        """Teksty tylko po polsku lub angielsku (ASCII + znaki diakrytyczne PL + stopien)."""
        # Dozwolone kody Unicode: ASCII drukowalne (32-126), litery polskie, znak stopnia (176).
        _POLISH_CODEPOINTS = frozenset({
            260, 261, 262, 263, 280, 281, 321, 322, 323, 324, 243, 346, 347, 377, 378, 379, 380,
        })
        _ALLOWED_EXTRA = _POLISH_CODEPOINTS | {176}  # stopien

        def _ok(text: str) -> bool:
            if not text:
                return True
            for ch in text:
                code = ord(ch)
                if code < 32 or code > 126:
                    if code not in _ALLOWED_EXTRA:
                        return False
            return True

        text_fields = [m.name_pl, m.name_en] + list(m.aliases)
        for field in text_fields:
            if not _ok(field):
                raise ValueError(
                    f"Niedozwolone znaki w polu tekstowym: {field!r} (id={m.id})"
                )
        desc = m.description
        for field in [
            desc.summary, desc.setup, desc.breathing,
            *desc.execution, *desc.cues, *desc.common_mistakes,
        ]:
            if not _ok(field):
                raise ValueError(
                    f"Niedozwolone znaki w opisie: {field!r} (id={m.id})"
                )
        return m


